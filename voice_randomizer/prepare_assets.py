"""Prepare all matching WAVs from the supplied 1st mod. Does not edit PACs."""
from pathlib import Path
import hashlib, io, json, re, struct, subprocess, sys, wave
from collections import Counter

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
from pac_index import pac_index

def main():
    destination = HERE / 'assets/old'
    destination.mkdir(parents=True, exist_ok=True)
    archives = sorted(p for p in (ROOT / '空之轨迹1st语音替换').rglob('*.7z')
                      if not p.parent.name.startswith('-'))
    sources = {}
    for archive in archives:
        listing = subprocess.check_output(['7z', 'l', '-slt', '-sccUTF-8', str(archive)]).decode('utf-8')
        wavs = re.findall(r'^Path = (.*[.]wav)\r?$', listing, re.M | re.I)
        for filename in wavs:
            assert re.fullmatch(r'v\d{3}_[a-z0-9_]+\.wav', filename), filename
            assert len(Path(filename).stem) <= 55, filename  # 64-byte game cache key, including alias.
            assert filename not in sources, f'Duplicate source: {filename}'
            sources[filename] = dict(archive=str(archive.relative_to(ROOT)),
                                     category=archive.parent.name.split('-', 1)[-1])
    assert sources, 'No source WAVs found'
    voice_pac = ROOT / 'pac/steam/voice.pac'
    entries = pac_index(voice_pac)
    table_pac = ROOT / 'pac/steam/table_sc.pac'
    te = pac_index(table_pac)['table_sc/t_voice.tbl']
    with table_pac.open('rb') as f:
        f.seek(te['offset']); table = f.read(te['size'])
    _, start, stride, count = struct.unpack_from('<IIII', table, 72)
    ids = {}
    for i in range(count):
        ident, _, at = struct.unpack_from('<iiQ', table, start + i * stride)
        name = table[at:table.index(0, at)].decode()
        ids[name] = ident
    for filename in sources:
        assert 'voice/wav/' + filename in entries, f'No game WAV for {filename}'
        assert Path(filename).stem in ids, f'No game voice ID for {filename}'
    for archive in archives:
        subprocess.run(['7z', 'e', '-y', '-bso0', str(archive), '-o' + str(destination), '*.wav'], check=True)
    manifest = []
    with voice_pac.open('rb') as f:
        for filename, source in sorted(sources.items()):
            p = destination / filename
            old = p.read_bytes()
            with wave.open(io.BytesIO(old), 'rb') as w:
                assert (w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getcomptype()) == (1, 2, 48000, 'NONE'), p
                duration = w.getnframes() / w.getframerate()
            entry = entries['voice/wav/' + p.name]
            f.seek(entry['offset']); new = f.read(entry['size'])
            with wave.open(io.BytesIO(new), 'rb') as w:
                assert (w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getcomptype()) == (1, 2, 48000, 'NONE'), p
                new_frames = w.getnframes()
                new_duration = w.getnframes() / w.getframerate()
            battle = re.fullmatch(r'v\d{3}_b(\d{4})(b?)', p.stem)
            number = int(battle[1]) if battle else ids[p.stem]
            label = '测试' if battle else {'主线语音':'剧情测试', '原野语音':'原野测试'}.get(source['category'], '主动语音测试')
            phrase = (f'{label}，{number}号' + ('，备用' if battle and battle[2] else '')) if new_duration >= 1.35 else '测试'
            manifest.append(dict(name=p.stem, voice_id=ids[p.stem], **source,
                                 placeholder_phrase=phrase, marker_number=number, new_frames=new_frames,
                                 old_sha256=hashlib.sha256(old).hexdigest(),
                                 old_seconds=duration, new_seconds=new_duration,
                                 new_sha256=hashlib.sha256(new).hexdigest()))
    assert len(manifest) == len(sources)
    (HERE / 'assets/manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    lines = ['// Generated by prepare_assets.py; all verified matching 1st voice assets.',
             'static const AssetDefinition kAssets[] = {']
    lines += ['    {"%s", %d},' % (x['name'], x['voice_id']) for x in manifest]
    lines += ['};']
    (HERE / 'src').mkdir(exist_ok=True)
    (HERE / 'src/assets.generated.h').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    print('Validated', len(manifest), 'old WAV files; original PACs untouched.')
    print('Categories:', dict(Counter(x['category'] for x in manifest)))
    print('Game duration range:', min(x['new_seconds'] for x in manifest), max(x['new_seconds'] for x in manifest))

if __name__ == '__main__':
    main()
